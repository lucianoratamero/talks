// Builds a hoshi-slides talk from markdown: writes index.html next to the .md file.
// Usage: npm run build:talk -- 2026/my-talk/slides.md   (or npm run watch:talk -- ... to rebuild on save)
// Docs: templates/hoshi-slides/README.md. Start from templates/hoshi-slides/example.md.
import { existsSync, readFileSync, watch, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const MARKER = '<!-- generated by scripts/build-talk.mjs, edit the markdown instead -->';
const escapeHtml = (s) => s.replace(/[&<>"]/g, (c) => `&#${c.charCodeAt(0)};`);

// birthday: June 15, 1989 (months are 0-based)
export const ageOn = (date) => date.getFullYear() - 1989 - (date >= new Date(date.getFullYear(), 5, 15) ? 0 : 1);

export function build(template, markdown) {
  const frontMatter = markdown.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!frontMatter) throw new Error('markdown must start with a --- front matter block (title, description, about)');
  const meta = {
    theme: 'light', // optional, so markdown written before dark mode existed still builds
    bullets: 'all', // `step` reveals list items one per click
    paragraphs: 'all', // `step` reveals paragraphs one per click
    age: String(ageOn(new Date())), // age at build time; `age:` in front matter pins it for an old talk
    ...Object.fromEntries([...frontMatter[1].matchAll(/^(\w+):(.*)$/gm)].map((m) => [m[1], m[2].trim()])),
  };
  if (!['light', 'dark'].includes(meta.theme)) throw new Error(`theme must be "light" or "dark", got "${meta.theme}"`);
  for (const key of ['bullets', 'paragraphs']) {
    if (!['all', 'step'].includes(meta[key])) throw new Error(`${key} must be "all" or "step", got "${meta[key]}"`);
  }

  // hoshi's look is the gradient <mark> on headings; leave `# comments` inside code fences alone. A trailing
  // `.element` comment moves in front of the <mark>: reveal attaches it to the element before it, so inside the
  // <mark> it would style the <mark>, while first in the heading it styles the heading itself
  let fenced = false;
  const slides = markdown.slice(frontMatter[0].length).split('\n').map((line) => {
    if (/^\s*(```|~~~)/.test(line)) fenced = !fenced;
    return fenced ? line : line.replace(/^(#{1,6})\s+(.*?)\s*(<!--\s*\.element\b.*?-->)?\s*$/,
      (whole, hashes, text, comment) => (text ? `${hashes} ${comment ? `${comment} ` : ''}<mark>${text}</mark>` : whole));
  }).join('\n').trim(); // trim: the plugin strips the first line's indentation from every line

  // placeholders first, so `{{ }}` inside slides (django/vue code) is never touched
  return template
    .replace(/\{\{(\w+)\}\}/g, (_, key) => {
      if (!(key in meta)) throw new Error(`front matter is missing "${key}"`);
      return escapeHtml(meta[key]);
    })
    // textarea content is entity-decoded by the browser, so escaping & and < round-trips the markdown exactly
    .replace(/<!-- slides:start -->[\s\S]*<!-- slides:end -->/, () => `${MARKER}
      <section data-markdown data-separator="^---$" data-separator-vertical="^--$" data-separator-notes="^Note:">
<textarea data-template>
${slides.replace(/&/g, '&amp;').replace(/</g, '&lt;')}
</textarea>
      </section>`);
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const watching = args.includes('--watch');
  const source = args.find((arg) => arg !== '--watch');
  if (!source) {
    console.error('usage: npm run build:talk -- [--watch] <year>/<talk>/slides.md');
    process.exit(1);
  }
  const out = join(dirname(source), 'index.html');
  if (existsSync(out) && !readFileSync(out, 'utf8').includes(MARKER)) {
    console.error(`${out} exists and was not generated from markdown; refusing to overwrite it.`);
    process.exit(1);
  }
  const templatePath = fileURLToPath(new URL('../templates/hoshi-slides/index.html', import.meta.url));
  const rebuild = () => {
    try {
      writeFileSync(out, build(readFileSync(templatePath, 'utf8'), readFileSync(source, 'utf8')));
      console.log(`wrote ${out}`);
    } catch (error) {
      if (!watching) throw error;
      console.error(`build failed: ${error.message}`); // keep watching; the next save may fix it
    }
  };
  rebuild();

  if (watching) {
    let timer;
    // watch folders, not files: editors that save via rename would silently drop a file watcher
    for (const file of [source, templatePath]) {
      watch(dirname(file), (_, name) => {
        if (name !== basename(file)) return;
        clearTimeout(timer); // one save fires several events
        timer = setTimeout(rebuild, 50);
      });
    }
    console.log('watching the markdown and the template, ctrl+c to stop');
  }
}
